BY_ID = {article['id']: article for article in ARTICLES}
CATEGORIES = list(dict.fromkeys(article['category'] for article in ARTICLES))
ALL = 'Todos os assuntos'


def normalize(value):
    value = unicodedata.normalize('NFKD', str(value or '').casefold())
    return ''.join(char for char in value if not unicodedata.combining(char))


def find_topics(category=ALL, query=''):
    words = normalize(query).split()
    matches = []
    for position, article in enumerate(ARTICLES):
        if category != ALL and article['category'] != category:
            continue
        title = normalize(article['title'])
        keywords = normalize(article['keywords'])
        body = normalize(article['body'])
        searchable = title + ' ' + keywords + ' ' + body
        if all(word in searchable for word in words):
            score = sum(4 * (word in title) + 2 * (word in keywords) for word in words)
            matches.append((-score, position, article))
    return [item[2] for item in sorted(matches, key=lambda item: item[:2])]


def render_topic(topic):
    article = BY_ID.get(topic)
    if not article:
        return '## Nenhum artigo encontrado\n\nExperimente outra palavra ou selecione **Todos os assuntos**. Você pode buscar nomes em inglês ou português, como `sampler`, `máscara` ou `seed`.'
    return f"**{article['category']}** · Axo Guide / Pedroltz\n\n" + article['body']


def view(category=ALL, query='', current=None, direction=0):
    matches = find_topics(category, query)
    ids = [article['id'] for article in matches]
    if not ids:
        return (gr.update(choices=[], value=None), render_topic(None), 'Nenhum resultado.',
                gr.update(interactive=False), gr.update(interactive=False))
    index = ids.index(current) if current in ids else 0
    index = min(max(index + direction, 0), len(ids) - 1)
    selected = ids[index]
    choices = [(article['title'], article['id']) for article in matches]
    status = f'Resultados: **{len(ids)}** · Artigo **{index + 1} / {len(ids)}**'
    return (gr.update(choices=choices, value=selected), render_topic(selected), status,
            gr.update(interactive=index > 0), gr.update(interactive=index < len(ids) - 1))


